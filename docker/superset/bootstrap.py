"""Superset provisioning — OpenWind reporting (track 3G, Stage 1).

Runs inside superset-init, after `superset db upgrade` and `superset init`.
Idempotent: compose re-runs it on every `up`, and a second run must change
nothing.

What it provisions, and why each piece is here:

  1. Revokes embedded-viewer permissions from the anonymous `Public` role
  2. Creates the dedicated `EmbeddedViewer` role with exactly those permissions
  3. Registers the platform database read-only, with SQL Lab exposure off
  4. Creates the two dashboards and marks them embeddable

Identifiers are never hardcoded here (spec R17). Dashboards are addressed by
slug, taken from configuration; the embedded UUID that the mint endpoint needs
is generated by Superset and resolved at runtime via
`GET /api/v1/dashboard/<slug>/embedded`, because it cannot be set by us.

Spec: docs/specs/superset-embedded-dashboarding.md
"""

import json
import logging
import os
import re
import sys

logging.basicConfig(level=logging.INFO, format="[bootstrap] %(message)s")
logger = logging.getLogger(__name__)

# The permissions an embedded dashboard actually needs to render.
#
# Read-only by design. Notably absent: any `all_datasource_access` or database
# grant. Guests do not need one — Superset's raise_for_access() special-cases an
# embedded guest user and grants datasource access implicitly, but only for
# charts on the dashboard their pass covers. Granting blanket datasource access
# would widen the blast radius for no benefit.
#
# FilterState write is deliberate: changing a dashboard filter persists filter
# state server-side, so read-only-everything breaks the filter bar. It writes
# cache state, never tenant data.
# Theme read permissions allow the guest session to load theme metadata in Superset 6+.
EMBEDDED_VIEWER_PERMISSIONS = [
    ("can_read", "Dashboard"),
    ("can_read", "Chart"),
    ("can_read", "Dataset"),
    ("can_explore_json", "Superset"),
    ("can_read", "DashboardFilterStateRestApi"),
    ("can_write", "DashboardFilterStateRestApi"),
    ("can_read", "Theme"),
    ("can_read", "ThemeRestApi"),
    # Found live on the 6.1.0 upgrade (2026-09-17): the embedded page's own
    # boot sequence calls GET /api/v1/me/roles/ and 403s without this,
    # breaking the whole embed (not just theming) — a permission check that
    # either didn't exist or wasn't enforced this early in 6.0.0. FAB's
    # permission name is can_<permission_name> on <ClassName>; this class sets
    # neither class_permission_name nor method_permission_name, so it's the
    # bare class name, not the resource_name ("me") used in its URL.
    ("can_read", "CurrentUserRestApi"),
    # Found live, not anticipated: the Date Range filter widget calls
    # GET /api/v1/time_range/ to parse and preview a phrase like "Last 7 days"
    # before applying it — a plain browser network request, not something a
    # dashboard/chart/dataset permission covers. Without this the request
    # itself 403s with {"message": "Access is Denied"}, which the browser
    # then also shows as a native cross-origin dialog because the failure
    # surfaces from inside the sandboxed iframe. class Api's method
    # `time_range` is decorated @has_access_api, and FAB's permission name for
    # an undecorated method on that class is can_<method name> — confirmed
    # against the running instance, not assumed from a doc.
    ("can_time_range", "Api"),
]

# Flask-AppBuilder's anonymous role. AUTH_ROLE_PUBLIC defaults to "Public", so
# anything granted here is granted to every unauthenticated visitor.
ANONYMOUS_ROLE_NAME = "Public"


def revoke_anonymous_embed_permissions(security_manager, db) -> None:
    """Strip embedded-viewer permissions from the anonymous role.

    This is not hypothetical cleanup. An earlier revision of this stack set
    GUEST_ROLE_NAME = "Public" and granted these six permissions to it, which
    handed them to every unauthenticated visitor — verified against a running
    instance at the time: GET /api/v1/dashboard/ with no auth answered 200
    rather than 401.

    Pointing GUEST_ROLE_NAME at a dedicated role does NOT undo that. The grants
    already written to the metadata database stay exactly where they are, so any
    deployment that ever ran the old configuration keeps the anonymous access
    while appearing fixed. That is the failure mode this function exists to
    close, and it is why the revoke runs before anything else here.
    """
    anon_role = security_manager.find_role(ANONYMOUS_ROLE_NAME)
    if not anon_role:
        logger.info("no %s role present, nothing to revoke", ANONYMOUS_ROLE_NAME)
        return

    revoked = 0
    for perm_name, view_name in EMBEDDED_VIEWER_PERMISSIONS:
        pv = security_manager.find_permission_view_menu(perm_name, view_name)
        if pv and pv in anon_role.permissions:
            security_manager.del_permission_role(anon_role, pv)
            revoked += 1

    db.session.commit()
    if revoked:
        logger.warning(
            "revoked %d embedded-viewer permission(s) from the anonymous '%s' "
            "role — unauthenticated callers had dashboard read access",
            revoked,
            ANONYMOUS_ROLE_NAME,
        )
    else:
        logger.info("anonymous '%s' role holds no embedded-viewer permissions", ANONYMOUS_ROLE_NAME)

    logger.info(
        "anonymous '%s' role now holds %d permission(s) in total",
        ANONYMOUS_ROLE_NAME,
        len(anon_role.permissions),
    )


def ensure_guest_role(security_manager, db, role_name: str) -> None:
    """Create the dedicated guest role and grant it exactly the six permissions."""
    if role_name == ANONYMOUS_ROLE_NAME:
        # Fail loudly rather than provision the exact configuration the revoke
        # above exists to undo.
        raise SystemExit(
            f"GUEST_ROLE_NAME is '{ANONYMOUS_ROLE_NAME}' — that is Flask-AppBuilder's "
            "anonymous role, so embedded-viewer permissions would be granted to every "
            "unauthenticated visitor. Set it to a dedicated role name (spec R6)."
        )

    role = security_manager.find_role(role_name)
    if not role:
        role = security_manager.add_role(role_name)
        logger.info("created role '%s'", role_name)

    granted, missing = 0, []
    for perm_name, view_name in EMBEDDED_VIEWER_PERMISSIONS:
        pv = security_manager.find_permission_view_menu(perm_name, view_name)
        if not pv:
            # Surfaced, not silently skipped — a permission that does not exist
            # in this Superset build would otherwise show up later as an
            # unexplained 403 inside the embed, which is a much worse thing to
            # debug than a line in the provisioning log.
            missing.append(f"{perm_name} on {view_name}")
            continue
        if pv not in role.permissions:
            security_manager.add_permission_role(role, pv)
            granted += 1

    db.session.commit()
    logger.info(
        "guest role '%s': %d permission(s) added, %d total",
        role_name,
        granted,
        len(role.permissions),
    )
    if missing:
        logger.warning("permissions not found in this Superset build: %s", missing)


def ensure_service_account(security_manager, db, username: str, password: str):
    """Create the backend-only account the API mints passes with.

    Least privilege, and specifically not Admin. Minting a guest token needs
    exactly one Superset permission — `can_grant_guest_token` on the
    `SecurityRestApi` view — so that is all this role gets. Measured on a running instance before
    this was written: the account had been given the built-in Admin role and its
    167 permissions, which is a full-control credential sitting in an
    environment variable for the sake of one API call.

    The password is reasserted on every run. Flask-AppBuilder's user creation is
    a no-op when the username already exists, so without this a rotated
    SUPERSET_SERVICE_ACCOUNT_PASSWORD would appear to apply and silently leave
    the old one in place — the same trap as the admin password in init.sh.
    """
    role_name = "ReportingServiceAccount"
    role = security_manager.find_role(role_name)
    if not role:
        role = security_manager.add_role(role_name)
        logger.info("created role '%s'", role_name)

    # Verified against this image's own permission table, not inferred from
    # where the methods are defined in the source.
    #
    # `can_read` on `SecurityRestApi` is required for the CSRF-token step of
    # the mint path (GET /api/v1/security/csrf_token/, decorated
    # @permission_name("read")); without it the account can log in but every
    # mint attempt 403s at the very next call, which reads like a credential
    # problem rather than a missing grant. Confirmed by testing this account
    # end-to-end, not assumed from reading the decorator.
    #
    # `can_read` on `Dashboard` is required separately — found live, not
    # anticipated: dashboards are addressed by slug (spec R17, never a
    # hardcoded UUID), so the mint path resolves the embedded id at request
    # time via GET /api/v1/dashboard/<slug>/embedded
    # (superset-client.ts:resolveEmbeddedId), which is decorated
    # @permission_name("read") against the Dashboard view menu — the same
    # permission the earlier comment above already covered for a different
    # endpoint, on a different view menu. The two are easy to conflate; they
    # are not the same grant.
    #
    # `can_read` on `Dataset` — found the same way, by calling the real
    # endpoint as this account rather than as admin: GET /api/v1/dataset/
    # (superset-client.ts:resolveDatasetId, added for dataset-scoped row
    # filters) is `DatasetRestApi`, `class_permission_name = "Dataset"`,
    # and returned 403 without this. Three endpoints, three view menus, three
    # separate grants — none of them implied by the others.
    required = [
        ("can_read", "SecurityRestApi"),
        ("can_grant_guest_token", "SecurityRestApi"),
        ("can_read", "Dashboard"),
        ("can_read", "Dataset"),
        # `can_read` on `Chart` — needed so the mint path can resolve a KPI
        # tile's numeric chart id by name (GET /api/v1/chart/?q=...,
        # superset-client.ts:resolveChartId), the same way it already
        # resolves dataset ids by table name. Added when the four KPI cards
        # moved out of the embedded iframe into admin-ui's own custom cards —
        # those cards query Superset's chart/data endpoint directly and need
        # the chart id, which this account did not previously have any reason
        # to look up. Found live: the lookup 403'd without it.
        ("can_read", "Chart"),
    ]
    for perm_name, view_name in required:
        pv = security_manager.find_permission_view_menu(perm_name, view_name)
        if not pv:
            raise SystemExit(
                f"{perm_name} on {view_name} not found in this Superset build — "
                "the mint endpoint cannot work without it"
            )
        if pv not in role.permissions:
            security_manager.add_permission_role(role, pv)
            logger.info("granted %s on %s to '%s'", perm_name, view_name, role_name)

    user = security_manager.find_user(username=username)
    if user:
        # Reassert both the role set and the password: an account left over from
        # an earlier revision may hold Admin.
        previous = [r.name for r in user.roles]
        if previous != [role_name]:
            logger.warning(
                "service account '%s' held roles %s — replacing with ['%s']",
                username,
                previous,
                role_name,
            )
        user.roles = [role]
        security_manager.reset_password(user.id, password)
        db.session.commit()
        logger.info("service account '%s' reconciled", username)
        return user

    created = security_manager.add_user(
        username=username,
        first_name="Reporting",
        last_name="Service",
        email=f"{username}@openwind.local",
        role=role,
        password=password,
    )
    if not created:
        raise SystemExit(f"could not create Superset service account '{username}'")
    return created
    db.session.commit()
    logger.info("created service account '%s' with role '%s'", username, role_name)


def ensure_analyst_roles(security_manager, db, database):
    """The two roles a Zitadel login can land in (Stage 2).

    Split deliberately. Everyone who authenticates gets an account, so "can log
    in" and "can query" have to be different states — otherwise the only way to
    deny someone is to stop them logging in, which looks like an outage and
    tells them nothing.

    ReportingNoAccess is where a login lands when its claims carry no analyst
    role: the session works and shows nothing. ReportingAnalyst adds SQL Lab
    over the reporting connection — safe only because that connection is row
    filtered per user and reaches six tables (migrations 0112 and 0113), not
    because of anything configured here.

    Tenant scoping is deliberately *not* one of these roles: it is bound per
    login as a `tenant:<uuid>` role by the security manager, so it cannot be
    handed out by editing a shared role in the Superset UI.
    """
    no_access = security_manager.find_role("ReportingNoAccess")
    if no_access is None:
        security_manager.add_role("ReportingNoAccess")
        logger.info("created role 'ReportingNoAccess' (deliberately empty)")

    # docs/specs/superset-standalone-with-zitadel.md T18 — a pure dashboard-
    # visibility marker, not a capability grant. Everyone who can query at
    # all (staff and non-staff alike) already holds ReportingAnalyst, which
    # is what SQL Lab and row-scoped charts run on (migration 0116 narrows
    # the rows, not the role). Without this, "My Organisation Overview"'s
    # only gate was the same ReportingAnalyst role everyone has, so a
    # non-staff login could open the tenant-wide dashboard directly — it
    # would show only their own rows (0116 holds regardless), but the
    # *dashboard itself* being reachable is a real behavioral difference
    # from the embedded path, where guest-token.ts 403s the tenant
    # dashboard for non-staff server-side. AUTH_ROLES_MAPPING in
    # superset_config.py grants this only to admin/agent.
    if security_manager.find_role("ReportingStaff") is None:
        security_manager.add_role("ReportingStaff")
        logger.info("created role 'ReportingStaff' (dashboard-visibility marker, no permissions of its own)")

    analyst = security_manager.find_role("ReportingAnalyst")
    if analyst is None:
        analyst = security_manager.add_role("ReportingAnalyst")
        logger.info("created role 'ReportingAnalyst'")

    wanted = [
        # "SQL Lab" is only the *category* (rendered as "SQL"). Granting it
        # alone produces exactly what was reported live: a top-level "SQL"
        # item with url=None and zero children, so clicking it does nothing.
        # The three links inside it are registered under their own view
        # names, not their display labels (superset/initialization/
        # __init__.py: add_link("SQL Editor", label="SQL Lab"),
        # add_link("Saved Queries", ...), add_link("Query Search",
        # label="Query History")) -- each needs its own menu_access or it is
        # filtered out of the dropdown.
        ("menu_access", "SQL Lab"),
        ("menu_access", "SQL Editor"),
        ("menu_access", "Saved Queries"),
        ("menu_access", "Query Search"),
        # Same class of gap: without these the role can *open* a dashboard by
        # URL but has no navigation to reach one, which is how a standalone
        # login ended up with a menu containing nothing but a dead "SQL".
        ("menu_access", "Dashboards"),
        ("menu_access", "Charts"),
        # Datasets is the front door to Explore, which is the only
        # point-and-click way to ask a new question here — pick a dataset, add
        # filter rows, choose a grouping, no SQL typed. Without it an analyst
        # who is not a developer can only look at charts somebody else already
        # built, because the one surface they could compose in (SQL Lab) asks
        # them to write SQL.
        #
        # Both the category and the link, for the same reason the SQL block
        # above grants four entries: "Data" is the dropdown and "Datasets" is
        # the item inside it, registered under its own view name. Granting the
        # category alone produces a menu that opens onto nothing.
        #
        # "Databases" is deliberately NOT granted. It lists connection records,
        # which an analyst has no reason to see and which name the credential
        # the reporting connection uses.
        ("menu_access", "Data"),
        ("menu_access", "Datasets"),
        ("can_sqllab", "Superset"),
        # The SQL Lab REST API is gated separately from the legacy
        # can_sqllab permission above: SqlLabRestApi sets
        # class_permission_name = "SQLLab" (superset/sqllab/api.py), so
        # GET /api/v1/sqllab/ 403s without can_read -- which is exactly how
        # it presented: menu opens, editor renders, every call forbidden.
        #
        # There is no "can_write on SQLLab" in this build (checked against
        # the live permission table, not assumed); the write side is split
        # into one permission per route. Granting the four below covers
        # running a query end to end: execute, poll for results, the cost
        # estimate the editor requests before running, and the format
        # button.
        ("can_read", "SQLLab"),
        ("can_execute_sql_query", "SQLLab"),
        ("can_get_results", "SQLLab"),
        ("can_estimate_query_cost", "SQLLab"),
        ("can_format_sql", "SQLLab"),
        # DELIBERATELY NOT GRANTED: can_export_csv / can_export_streaming_csv.
        # docs/specs/superset-standalone-with-zitadel.md R7 and §C "export"
        # treat export as a separate risk from query cost ("row caps bound
        # query cost, not exfiltration volume") and T12 -- export-specific
        # rate limiting -- is still todo. Granting them here would open an
        # unbounded bulk-export path before that exists. Add them in the
        # same change that lands T12, not before.
        ("can_read", "SavedQuery"),
        ("can_write", "SavedQuery"),
        ("can_read", "Query"),
        ("can_read", "Chart"),
        ("can_write", "Chart"),
        ("can_read", "Dashboard"),
        # The interactive equivalents of what EMBEDDED_VIEWER_PERMISSIONS
        # already grants the guest role, plus the ones only a real logged-in
        # user hits. Found by diffing this role against EmbeddedViewer and
        # checking each against the live permission table -- not by waiting
        # for the next 403.
        #
        # filter_state: the dashboard filter bar persists its selection via
        # POST /api/v1/dashboard/<id>/filter_state. Same pair the guest role
        # has had all along; without it every filter interaction 403s.
        ("can_read", "DashboardFilterStateRestApi"),
        ("can_write", "DashboardFilterStateRestApi"),
        # form_data: Explore stores chart state here, so "Create chart from
        # SQL Lab results" and any drill into a chart needs it. The guest
        # role never does either, which is why it isn't in that list.
        ("can_read", "ExploreFormDataRestApi"),
        ("can_write", "ExploreFormDataRestApi"),
        # Permalinks: "copy permalink" on a dashboard or an explore view.
        # These only store a state blob keyed by id -- opening one still runs
        # the same dashboard/dataset access checks -- so they widen sharing
        # convenience, not data reach.
        ("can_read", "DashboardPermalinkRestApi"),
        ("can_write", "DashboardPermalinkRestApi"),
        ("can_read", "ExplorePermalinkRestApi"),
        ("can_write", "ExplorePermalinkRestApi"),
        # Same 6.1.0 boot-sequence call the embedded path hit (see
        # EMBEDDED_VIEWER_PERMISSIONS' own note): GET /api/v1/me/roles/.
        ("can_read", "CurrentUserRestApi"),
        ("can_read", "Theme"),
        ("can_read", "Dataset"),
        ("can_read", "Database"),
        ("can_explore", "Superset"),
        ("can_explore_json", "Superset"),
        # The Explore REST API is gated separately from the legacy
        # can_explore permission above — exactly the same split as SQL Lab
        # (see the can_sqllab / can_read-on-SQLLab pair earlier in this list),
        # and missed here for the same reason: the legacy name reads like it
        # covers the feature.
        #
        # ExploreRestApi sets class_permission_name = "Explore", so
        # GET /api/v1/explore/?datasource_type=table&datasource_id=N answers
        # 403 without this. Confirmed from a real session: opening a dataset
        # from the Datasets list rendered "Missing dataset — the dataset linked
        # to this chart may have been deleted", zero metrics, zero columns and
        # a FORBIDDEN toast, while the dataset was present and healthy. The
        # error names the wrong cause, which is what made it worth writing down.
        ("can_read", "Explore"),
        # Filter dropdowns in Explore fetch their options through this. Without
        # it a filter row can be added but its value list stays empty, which is
        # the whole point of point-and-click filtering.
        ("can_get_column_values", "Datasource"),
        # Explore asks for a dataset's column/metric metadata on open. Granted
        # by name only; can_save on Datasource is deliberately NOT granted,
        # since editing a dataset is not an analyst's job.
        ("can_external_metadata_by_name", "Datasource"),
        ("can_dashboard", "Superset"),
        # Same gap found on the embedded guest role: the Date Range widget
        # calls GET /api/v1/time_range/ to parse the chosen phrase.
        ("can_time_range", "Api"),
        # The landing page asks for the viewer's own recent activity as soon as
        # it loads. Without this the first thing a successfully authenticated
        # analyst sees is "There was an issue fetching your recent activity:
        # Forbidden" — a working login that reads as a broken one.
        ("can_recent_activity", "Log"),
        # Charts and dashboards render through these; a role that can open a
        # dashboard but not fetch its data shows a page of failed tiles.
        ("can_csv", "Superset"),
        ("can_fetch_datasource_metadata", "Superset"),
        ("can_samples", "Datasource"),
        ("can_read", "CssTemplate"),
        ("can_read", "Annotation"),
        ("can_read", "Tag"),
    ]
    granted = 0
    for action, view in wanted:
        pvm = security_manager.find_permission_view_menu(action, view)
        if pvm is None:
            # Permission names drift between Superset versions. A missing one
            # is logged rather than fatal, so a version bump degrades the role
            # instead of breaking provisioning for every stage.
            logger.warning("permission %s on %s not found — skipped", action, view)
            continue
        if pvm not in analyst.permissions:
            security_manager.add_permission_role(analyst, pvm)
            granted += 1

    # Access to the reporting connection itself, which is what makes SQL Lab
    # usable. Granted on the one managed database, never on all databases.
    db_pvm = security_manager.find_permission_view_menu(
        "database_access", database.perm
    )
    if db_pvm is not None and db_pvm not in analyst.permissions:
        security_manager.add_permission_role(analyst, db_pvm)
        granted += 1

    db.session.commit()
    logger.info(
        "role 'ReportingAnalyst' ready (%d permission(s) added this run)", granted
    )
    return analyst


def ensure_reporting_database(db, database_name: str, sqlalchemy_uri: str):
    """Register the platform database as a read-only reporting source.

    `expose_in_sqllab=False` is the load-bearing setting here, and it is set
    explicitly because the column defaults to True. There is no config switch
    that disables SQL Lab globally (checked against this image's own
    superset/config.py — SQLLAB_BACKEND_PERSISTENCE is about persisting query
    tabs, not access), so keeping arbitrary SQL off this connection is done per
    database, right here.

    That matters more than usual on this particular connection: it reaches the
    platform database, so an arbitrary-SQL surface on it is only as safe as the
    database-side boundaries under it (row-level security with no bypass, the
    column allowlist and the own-rows policy; migrations 0112-0124).
    """
    from superset.models.core import Database

    database = db.session.query(Database).filter_by(database_name=database_name).one_or_none()
    created = database is None
    if created:
        database = Database(database_name=database_name)

    database.set_sqlalchemy_uri(sqlalchemy_uri)
    # SQL Lab is what Stage 2 *is* — an analyst writing their own queries — so
    # it opens only when Stage 2 is switched on, and stays shut otherwise.
    #
    # Opening it was unsafe until two things were true, and both now are: row
    # filtering applies to this connection (migration 0112 removed the role's
    # BYPASSRLS), and the role reaches only the six reporting tables (0113 cut
    # it from 34). Without the second, a hand-written query could read
    # `tenants`, which has no tenant column and returns every row to anyone.
    database.expose_in_sqllab = bool(
        os.environ.get("SUPERSET_OAUTH_CLIENT_ID", "").strip()
    )
    # Writes through the reporting connection are never legitimate — it is a
    # read-only role, and these flags failing closed means a misconfiguration
    # surfaces as a refusal rather than a mutation.
    database.allow_dml = False
    database.allow_ctas = False
    database.allow_cvas = False

    if created:
        db.session.add(database)
    db.session.commit()

    logger.info(
        "reporting database '%s' %s (expose_in_sqllab=%s, allow_dml=%s)",
        database_name,
        "created" if created else "updated",
        database.expose_in_sqllab,
        database.allow_dml,
    )
    return database


def close_sqllab_exposure_elsewhere(db, managed_database_name: str) -> None:
    """Turn off SQL Lab exposure on every other registered database.

    Provisioning that only creates correct state is not enough — it has to
    correct state left behind by earlier revisions of itself. This was found on
    a running instance: an older revision registered the platform database
    under a different name with expose_in_sqllab=True, and creating a second,
    correctly-configured entry did nothing to close the first. The instance had
    an arbitrary-SQL surface on the platform database while provisioning
    reported success.

    Same failure shape as the anonymous-role grants above: the fix appears
    applied because the new object is right, while the old object is what an
    attacker would actually reach.

    Non-destructive by choice — the connection is left registered and only its
    SQL Lab exposure is closed, so an operator who wants it back can restore it
    deliberately rather than having to reconstruct a deleted connection.
    """
    from superset.models.core import Database

    others = (
        db.session.query(Database)
        .filter(Database.database_name != managed_database_name)
        .filter(Database.expose_in_sqllab.is_(True))
        .all()
    )
    if not others:
        logger.info("no other database has SQL Lab exposure enabled")
        return

    for database in others:
        database.expose_in_sqllab = False
        logger.warning(
            "closed SQL Lab exposure on database '%s' (id=%s) — Stage 1 permits "
            "no arbitrary-SQL surface on the reporting connection",
            database.database_name,
            database.id,
        )
    db.session.commit()


# Datasets that must not exist any more, and why. Provisioning that only creates
# correct state is not enough — it has to correct state left behind by earlier
# revisions of itself, the same lesson close_sqllab_exposure_elsewhere above was
# written for.
RETIRED_DATASETS = {
    # The view was dropped by migration 0119: it read `metadata` in order to
    # redact it, while 0112's security_invoker meant the caller needed that
    # column anyway, so it never returned a row. Event classification now comes
    # from workflow_events.event_type (0117).
    "workflow_events_masked",
    # The raw event table was registered as a dataset but granted to no role.
    # Its payload column is no longer readable by reporting at all (0118), so a
    # dataset pointing at it can only mislead.
    "workflow_events",
}


def remove_retired_datasets(db, managed_database_name: str) -> None:
    """Drop datasets that are retired, or stranded on a superseded connection.

    Two kinds of leftover, both found on a running instance:

      1. Datasets named in RETIRED_DATASETS, whose underlying object is gone.
         Left in place they appear in Explore and in the dataset list as
         something an analyst can pick, then fail at query time.
      2. Datasets attached to any database other than the managed one. An
         earlier revision registered the platform database under a different
         name; the datasets hanging off it survived the rename and still
         advertise tables against a connection nothing maintains.

    Refuses to remove anything a chart is built on. A dataset with slices is
    load-bearing whatever its name suggests, and deleting it would take the
    chart with it — so that case is logged loudly and skipped rather than
    guessed at.
    """
    from superset.connectors.sqla.models import SqlaTable
    from superset.models.core import Database
    from superset.models.slice import Slice

    managed = (
        db.session.query(Database)
        .filter_by(database_name=managed_database_name)
        .one_or_none()
    )

    candidates = []
    for dataset in db.session.query(SqlaTable).all():
        if dataset.table_name in RETIRED_DATASETS:
            candidates.append((dataset, "retired"))
        elif managed is not None and dataset.database_id != managed.id:
            candidates.append((dataset, "stranded on a superseded connection"))

    if not candidates:
        logger.info("no retired or stranded datasets to remove")
        return

    removed = 0
    for dataset, reason in candidates:
        charts = (
            db.session.query(Slice)
            .filter(Slice.datasource_id == dataset.id)
            .count()
        )
        if charts:
            logger.warning(
                "dataset '%s' (id=%s) is %s but %d chart(s) depend on it — "
                "left in place; remove the charts first",
                dataset.table_name,
                dataset.id,
                reason,
                charts,
            )
            continue
        logger.warning(
            "removing dataset '%s' (id=%s): %s",
            dataset.table_name,
            dataset.id,
            reason,
        )
        db.session.delete(dataset)
        removed += 1

    db.session.commit()
    logger.info("removed %d retired/stranded dataset(s)", removed)


def ensure_dataset(
    db,
    security_manager,
    reporting_role,
    database,
    table_name: str,
    main_dttm_col: str,
    sql: str | None = None,
    columns: list[dict] | None = None,
    calculated_columns: list[dict] | None = None,
):
    """Register a dataset — a physical table, or a SQL-defined virtual one — and return it.

    Datasets are what charts are built against, and what a row filter can be
    scoped to — a filter with no dataset named is applied by Superset to every
    dataset on the dashboard, with the clause injected as raw SQL and no column
    checking (Stage 1 §I). That is why this runs before any filter scoping: the
    `dataset` field on an RLS rule is a numeric id, and the id does not exist
    until the dataset does.

    `main_dttm_col` is set deliberately rather than left to Superset's default.
    Time-series charts need a designated time column, and without one every
    trend tile silently falls back to no time grain.

    `sql`, when given, makes this a virtual dataset — Superset's own sanctioned
    place for a window function. Chart-level filters cannot express one
    ("sum of all visits to a state" needs LEAD() over workflow_events, and
    Superset's ADHOC_SUBQUERY_NOT_ALLOWED_ERROR blocks a sub-query at that
    layer, verified live) — but the dataset's own defining query is raw SQL by
    nature and is not subject to that restriction. Every such query in this
    file selects `tenant_id` from the underlying table, unmodified, so the
    tenant row filter still has a real column to bind to; a virtual dataset
    that dropped or renamed it would silently defeat isolation.

    `columns`, required whenever `sql` is given, is `[{"name", "type",
    "is_dttm"?}, ...]`. Superset's own auto-introspection for a virtual
    dataset infers columns from a sample row (superset/result_set.py), and RLS
    correctly returns zero sample rows to a provisioning-time connection with
    no tenant identity to stamp — the isolation design working as intended,
    colliding with an introspection method that assumes it can always read
    one. Declaring the columns explicitly is the fix; leaving them to
    inference is not a smaller version of the same fix, it is silent failure
    (confirmed live: 0 columns, no exception, `dataset.fetch_metadata()`
    reports success).
    """
    from superset.connectors.sqla.models import SqlaTable

    dataset = (
        db.session.query(SqlaTable)
        .filter_by(table_name=table_name, database_id=database.id)
        .one_or_none()
    )
    created = dataset is None
    if created:
        dataset = SqlaTable(
            table_name=table_name,
            database_id=database.id,
            schema="public" if sql is None else None,
        )
        db.session.add(dataset)

    dataset.main_dttm_col = main_dttm_col
    if sql is not None:
        dataset.sql = sql
    db.session.commit()

    # Column and metric metadata is what Superset reads to offer fields in the
    # chart builder. Without this the dataset registers but appears to have no
    # columns at all.
    dataset.fetch_metadata()
    db.session.commit()

    # A virtual dataset built on an RLS-protected table introspects as zero
    # columns during provisioning, every time — not a transient failure.
    # Traced to the actual mechanism, not assumed: Superset infers a virtual
    # dataset's columns from a sample row via pandas (superset/result_set.py),
    # not from the driver's cursor.description (confirmed populated correctly
    # with all 5 real columns in isolation). Provisioning has no tenant
    # identity to stamp onto the connection, so RLS correctly returns zero
    # rows here — the same fail-closed behaviour the whole isolation design
    # relies on — and zero rows means pandas has nothing to infer a schema
    # from. This is not a bug to route around with a broader grant; it is the
    # isolation design working as intended, colliding with an introspection
    # method that assumes it can always read a sample row.
    #
    # The fix is to describe the columns once, here, rather than depend on
    # inference that structurally cannot succeed for this class of dataset.
    if sql is not None and columns is not None:
        from superset.connectors.sqla.models import TableColumn

        existing = {c.column_name: c for c in dataset.columns}
        added = 0
        for col in columns:
            column = existing.get(col["name"])
            if column is None:
                column = TableColumn(
                    table_id=dataset.id,
                    column_name=col["name"],
                    groupby=True,
                    filterable=True,
                )
                db.session.add(column)
                added += 1
            # Synced on every run, not only at creation. An earlier revision
            # declared columns only when the dataset had none at all, which
            # made the declaration a one-shot: adding a column to a virtual
            # dataset's SQL later changed the query but never produced the
            # TableColumn, so the new column existed in the results and was
            # invisible to every chart.
            column.type = col["type"]
            column.is_dttm = col.get("is_dttm", False)
            column.verbose_name = col.get("verbose_name")
            # Surfaces as the hover tooltip on the column, which is where a
            # reader asks "what does this number actually measure" — a figure
            # like "Days" or "First Response" is ambiguous without it, and the
            # answer belongs next to the number rather than in a document.
            column.description = col.get("description")

        # Columns the config no longer declares are dropped, so removing one
        # from the SQL removes it from the chart builder too rather than
        # leaving a control that errors when used.
        declared = {col["name"] for col in columns}
        removed = [c for c in dataset.columns if c.column_name not in declared]
        for column in removed:
            db.session.delete(column)

        db.session.commit()
        logger.info(
            "dataset '%s': %d column(s) declared (%d added, %d removed) — RLS "
            "blocks every sample row at provisioning time, so "
            "introspection-by-sampling cannot see them",
            table_name,
            len(columns),
            added,
            len(removed),
        )

    # Drop any column the reporting role is not allowed to read.
    #
    # A dataset that advertises a column the query will be refused for is worse
    # than one that omits it: the column shows up in Explore as something an
    # analyst can pick, and picking it returns a permission error rather than a
    # result. That happened here — migrations 0118 and 0122 withdrew the two
    # payload columns (`workflow_events.metadata`, `entity_instances.fields`)
    # plus `search_vector` and the `origin_*` set, and the dataset went on
    # offering them.
    #
    # Asked of the database rather than kept as a list here, so this tracks the
    # grants instead of drifting from them: the next revoke prunes itself, and a
    # column that is granted back reappears through normal introspection.
    #
    # Physical datasets only. A virtual dataset's columns come from its own
    # SELECT list, which cannot name a column the role may not read — if it did,
    # the dataset would fail wholesale rather than per column.
    if not sql:
        from sqlalchemy import text as _text

        exposed = [c for c in dataset.columns if not (c.expression or "")]
        if exposed:
            with database.get_sqla_engine() as engine:
                with engine.connect() as conn:
                    readable = {
                        row[0]
                        for row in conn.execute(
                            _text(
                                "SELECT column_name FROM information_schema."
                                "column_privileges WHERE grantee = :role "
                                "AND table_name = :tbl"
                            ),
                            {
                                "role": os.environ.get(
                                    "SUPERSET_REPORTING_DB_ROLE", "analytics_user"
                                ),
                                "tbl": table_name,
                            },
                        )
                    }

            # An empty answer means the question failed, not that the role may
            # read nothing — pruning every column on that reading would empty
            # the dataset. Only act on a positive list.
            if readable:
                pruned = [c for c in exposed if c.column_name not in readable]
                for column in pruned:
                    logger.warning(
                        "dataset '%s': dropping column '%s' — not readable by the "
                        "reporting role",
                        table_name,
                        column.column_name,
                    )
                    db.session.delete(column)
                if pruned:
                    db.session.commit()
            else:
                logger.warning(
                    "dataset '%s': could not read column privileges — left the "
                    "column list alone",
                    table_name,
                )

    # Calculated columns — a derived column expressed in SQL and stored against
    # the dataset, so every chart built on it gets the same derivation.
    #
    # This is the only way to reshape a value on a *physical* dataset: there is
    # no defining query to edit, so `current_state` arrives exactly as the
    # table stores it — `in_progress`. Doing the same tidy-up in each tile
    # instead would mean every new chart re-deriving it, and the first one to
    # forget would quietly disagree with the others.
    if calculated_columns:
        from superset.connectors.sqla.models import TableColumn

        present = {c.column_name: c for c in dataset.columns}
        for col in calculated_columns:
            column = present.get(col["name"])
            if column is None:
                column = TableColumn(
                    table_id=dataset.id,
                    column_name=col["name"],
                    groupby=True,
                    filterable=True,
                )
                db.session.add(column)
            column.expression = col["expression"]
            column.type = col.get("type", "TEXT")
            column.verbose_name = col.get("verbose_name")
        db.session.commit()
        logger.info(
            "dataset '%s': %d calculated column(s) synced",
            table_name,
            len(calculated_columns),
        )

    # Ownership was tried here first, matching the dashboard fix above, and it
    # did not work — checked, rather than assumed to be equivalent. Dataset
    # visibility runs through a different filter entirely
    # (DatasourceFilter -> get_dataset_access_filters, superset/utils/
    # filters.py): accessible databases, OR a `datasource_access` permission
    # matching the dataset's own `perm` string, OR schema access. Ownership is
    # not one of the three. GET /api/v1/dataset/?q=... came back 200 (can_read
    # on Dataset was enough to pass the endpoint's own permission check) but
    # an empty result set (this row-level filter still hid it) — the same
    # "permission granted, row still invisible" shape as the dashboard bug,
    # with a different actual mechanism underneath. Two dead ends before this
    # was found: ownership does nothing here, and neither endpoint's 200
    # status meant the real data was reachable.
    #
    # `dataset.perm` is Superset's own string for exactly this dataset
    # (e.g. "[OpenWind Platform].[entity_instances](id:3)") and is
    # auto-registered as a `datasource_access` permission the moment the
    # dataset is created — granting it here, rather than something broader
    # like `all_datasource_access`, scopes the account to precisely the two
    # datasets it needs.
    datasource_pv = security_manager.find_permission_view_menu(
        "datasource_access", dataset.perm
    )
    if datasource_pv and datasource_pv not in reporting_role.permissions:
        security_manager.add_permission_role(reporting_role, datasource_pv)
        db.session.commit()
        logger.info(
            "granted datasource_access on '%s' to '%s'",
            dataset.perm,
            reporting_role.name,
        )

    logger.info(
        "dataset '%s' %s (id=%s, time column=%s, %d columns)",
        table_name,
        "created" if created else "updated",
        dataset.id,
        main_dttm_col,
        len(dataset.columns),
    )
    return dataset


def ensure_chart(
    db, dataset, dashboard, chart_name: str, viz_type: str, params: dict,
):
    """Create one chart against `dataset`, and attach it to `dashboard`.

    The `params` shape is not documented anywhere convenient — verified by
    creating a real chart through the running instance's own REST API first
    (POST /api/v1/chart/, then confirmed it returns real query data via
    POST /api/v1/chart/data), rather than assumed from a viz-type name.

    Attachment is via `dashboard.slices`, a separate step from creating the
    chart — a chart can exist without being on any dashboard, and creating one
    does not imply attachment. This is also where the empty-dashboard problem
    (OQ-6: two dashboards, zero charts, since the very first provisioning
    script) actually gets fixed — everything before this function created
    structure; this is the first thing that puts real content in it.
    """
    from superset.models.slice import Slice

    # Not .one_or_none(). Analysts can save charts from Explore, and a saved
    # copy under the same name on the same dataset made that call raise
    # MultipleResultsFound — which aborted provisioning entirely, so one user
    # clicking Save broke every later deploy. Found live on 2026-09-23 (a demo
    # "Save" created a second "Ticket SLA Watch(…)").
    #
    # The provisioned chart is the one attached to a dashboard; failing that,
    # the oldest. A user's copy is never modified or deleted here — it is
    # their content, and provisioning only owns what it created.
    matches = (
        db.session.query(Slice)
        .filter_by(slice_name=chart_name, datasource_id=dataset.id)
        .order_by(Slice.id)
        .all()
    )
    chart = next((s for s in matches if s.dashboards), matches[0] if matches else None)
    if len(matches) > 1:
        logger.warning(
            "chart '%s': %d charts share this name on dataset %s — updating id=%s "
            "(the provisioned one), leaving the others untouched",
            chart_name,
            len(matches),
            dataset.id,
            chart.id,
        )
    created = chart is None
    if created:
        chart = Slice(
            slice_name=chart_name,
            datasource_id=dataset.id,
            datasource_type="table",
        )
        db.session.add(chart)

    chart.viz_type = viz_type
    chart.params = json.dumps(params)
    db.session.commit()

    if chart not in dashboard.slices:
        dashboard.slices.append(chart)
        db.session.commit()
        logger.info("attached chart '%s' to dashboard '%s'", chart_name, dashboard.slug)

    logger.info(
        "chart '%s' %s (id=%s, viz_type=%s, dataset=%s)",
        chart_name,
        "created" if created else "updated",
        chart.id,
        viz_type,
        dataset.table_name,
    )
    return chart


def load_tile_config(path: str) -> dict:
    """Read the tile definitions.

    Tiles are configuration, not code: this file only applies what the YAML
    declares. Adding or retuning a tile is an edit to `tiles.yaml`, reviewable
    on its own, and the same file is what spec R12 wants kept in the repo so
    the Superset volume is never the only copy of the dashboard content.

    A missing file is fatal rather than skipped — provisioning that silently
    produced empty dashboards is exactly the state this work started from
    (OQ-6), and it took a while to notice.
    """
    import yaml

    if not os.path.exists(path):
        raise SystemExit(
            f"tile config not found at {path} — the dashboards would provision "
            "empty, which is indistinguishable from them being broken"
        )

    with open(path, encoding="utf-8") as fh:
        config = yaml.safe_load(fh) or {}

    tiles = config.get("tiles") or []
    if not tiles:
        raise SystemExit(f"{path} declares no tiles")

    filters = config.get("filters") or []
    logger.info(
        "loaded %d tile definition(s) and %d filter(s) from %s",
        len(tiles),
        len(filters),
        path,
    )
    return config


# Superset lays a dashboard out on a 12-column grid. These are the widths a
# tile gets when tiles.yaml does not name one, chosen so each kind is legible
# at its natural size: four counters to a row, two charts to a row, and a table
# alone on its own row because a table squeezed into half a row truncates the
# one column that identifies the record.
DEFAULT_TILE_WIDTHS = {
    "big_number_total": 3,
    "big_number": 3,
    "table": 12,
}
DEFAULT_TILE_WIDTH = 6
DEFAULT_TILE_HEIGHTS = {"table": 75}
DEFAULT_TILE_HEIGHT = 50
GRID_COLUMNS = 12


def build_position_json(placements: list[dict]) -> str:
    """Lay tiles out on the dashboard grid, packing rows left to right.

    Superset stores a dashboard's layout as its own tree, separate from the
    chart-to-dashboard link: attaching a chart makes it *belong* to the
    dashboard, but a dashboard whose position_json is empty has no layout to
    render it in, so every tile falls back to the same default box regardless
    of what it contains. Both are required, which is why this runs alongside
    the attachment rather than instead of it.

    Rows are packed rather than configured: a tile that would overflow the
    12-column grid starts a new row. That keeps tiles.yaml declaring what a
    tile *is* (a counter, a chart, a table) instead of where it sits, so
    reordering or adding one does not mean recomputing coordinates by hand.

    A native MARKDOWN caption tile below each chart was tried and abandoned
    here (2026-09-18), alongside two other native Superset mechanisms for a
    visible per-chart hint (`description`/`certification_details`, read via
    the chart header's info/certified icon): all three reach the frontend
    with correct data but none render usably on a dashboard tile in this
    Superset version — description/certification never render at all
    (aria-label only), and MARKDOWN renders but is capped at a fixed ~268px
    width regardless of the width declared, specifically for a row Superset's
    own interactive editor never touched. If a tile ever needs hint text, the
    big-number viz's own `subheader` param (tiles.yaml) is the one place it is
    confirmed to render, because that plugin reads it directly rather than
    routing through the header component the other three depend on. The 4
    KPI tiles deliberately carry none: the number and its title stand alone.
    """
    position: dict = {
        "DASHBOARD_VERSION_KEY": "v2",
        "ROOT_ID": {"type": "ROOT", "id": "ROOT_ID", "children": ["GRID_ID"]},
        "GRID_ID": {
            "type": "GRID",
            "id": "GRID_ID",
            "children": [],
            "parents": ["ROOT_ID"],
        },
    }

    row_index = 0
    row_id = None
    used = 0

    for placement in placements:
        width = max(1, min(GRID_COLUMNS, int(placement["width"])))
        if row_id is None or used + width > GRID_COLUMNS:
            row_index += 1
            row_id = f"ROW-{row_index}"
            used = 0
            position[row_id] = {
                "type": "ROW",
                "id": row_id,
                "children": [],
                "meta": {"background": "BACKGROUND_TRANSPARENT"},
                "parents": ["ROOT_ID", "GRID_ID"],
            }
            position["GRID_ID"]["children"].append(row_id)

        chart_key = f"CHART-{placement['chart_id']}"
        position[chart_key] = {
            "type": "CHART",
            "id": chart_key,
            "children": [],
            "meta": {
                "chartId": placement["chart_id"],
                "sliceName": placement["name"],
                "width": width,
                "height": int(placement["height"]),
                "uuid": placement["uuid"],
            },
            "parents": ["ROOT_ID", "GRID_ID", row_id],
        }
        position[row_id]["children"].append(chart_key)
        used += width

    return json.dumps(position)


def apply_tiles(db, tiles: list[dict], datasets: dict, dashboards: dict) -> tuple[dict, dict]:
    """Create every configured tile, attach it, and lay out each dashboard.

    Returns (charts_by_dataset, chart_id_by_name). Filters need charts_by_dataset
    to scope themselves by dataset: a filter names a column, and a column only
    exists on the charts built from its own dataset — pointing one at a chart
    on a different dataset makes that chart error rather than filter.
    chart_id_by_name additionally lets a filter scope itself to one or more
    specific tiles by name (a filter's `charts:` key), rather than every chart
    that shares its dataset.
    """
    placements: dict[str, list[dict]] = {key: [] for key in dashboards}
    charts_by_dataset: dict[tuple[str, str], list[int]] = {}
    chart_id_by_name: dict[str, int] = {}
    # Every chart this run provisioned for a dashboard, hidden ones included —
    # separate from `placements`, which only holds what actually renders in
    # the grid. Detachment below must check this, not placements: a hidden
    # tile is a real, current part of the config and must survive being
    # dropped from the visible layout, or every run would detach it right
    # after attaching it.
    all_tiles_by_dashboard: dict[str, set[int]] = {key: set() for key in dashboards}
    # Chart ids kept out of the grid on purpose (see the `hidden` branch
    # below). Leaving a chart out of position_json does not stop Superset
    # from rendering it — verified live: a chart attached to a dashboard but
    # absent from its layout is appended as an orphan at the bottom of the
    # page instead of being hidden. dashboard.css (a real, native Superset
    # field the dashboard page renders as a literal <style> tag) is the
    # mechanism that actually hides it.
    hidden_chart_ids_by_dashboard: dict[str, set[int]] = {
        key: set() for key in dashboards
    }

    for tile in tiles:
        missing = [k for k in ("name", "dashboard", "dataset", "viz_type") if not tile.get(k)]
        if missing:
            raise SystemExit(f"tile {tile!r} is missing required key(s): {missing}")

        dataset = datasets.get(tile["dataset"])
        if dataset is None:
            raise SystemExit(
                f"tile '{tile['name']}' names dataset '{tile['dataset']}', which is "
                f"not registered. Known datasets: {sorted(datasets)}"
            )

        dashboard = dashboards.get(tile["dashboard"])
        if dashboard is None:
            raise SystemExit(
                f"tile '{tile['name']}' names dashboard '{tile['dashboard']}', which is "
                f"not provisioned. Known dashboards: {sorted(dashboards)}"
            )

        # viz_type is repeated into params because Superset reads it from both
        # the column and the params blob, and disagreement between the two
        # renders an empty tile rather than an error.
        params = {"viz_type": tile["viz_type"], **(tile.get("params") or {})}

        chart = ensure_chart(
            db,
            dataset,
            dashboard,
            tile["name"],
            tile["viz_type"],
            params,
        )

        charts_by_dataset.setdefault(
            (tile["dashboard"], tile["dataset"]), []
        ).append(chart.id)
        chart_id_by_name[tile["name"]] = chart.id

        # `hidden: true` keeps the chart created, attached and permissioned —
        # which is what makes it a valid resource for the embedded guest-token
        # bypass (raise_for_access requires the chart to be in
        # dashboard.slices) — while leaving it out of the rendered grid. No
        # tile currently sets this (the four KPI numbers it was built for are
        # native tiles again as of D6), but the mechanism stays available for
        # a future tile that needs to exist without rendering in the grid.
        all_tiles_by_dashboard[tile["dashboard"]].add(chart.id)

        if tile.get("hidden"):
            hidden_chart_ids_by_dashboard[tile["dashboard"]].add(chart.id)
            continue

        placements[tile["dashboard"]].append(
            {
                "chart_id": chart.id,
                "uuid": str(chart.uuid),
                "name": tile["name"],
                "width": tile.get(
                    "width",
                    DEFAULT_TILE_WIDTHS.get(tile["viz_type"], DEFAULT_TILE_WIDTH),
                ),
                "height": tile.get(
                    "height",
                    DEFAULT_TILE_HEIGHTS.get(tile["viz_type"], DEFAULT_TILE_HEIGHT),
                ),
            }
        )

    # A tile dropped from the config has to be detached, not just left out of
    # the layout. Attachment and layout are separate records: rebuilding the
    # layout alone stops the chart rendering but leaves it attached, so it goes
    # on appearing in the dashboard's chart list and in anything that reasons
    # about the dashboard from its slices rather than its layout.
    for key, dashboard in dashboards.items():
        keep = all_tiles_by_dashboard[key]
        stale = [s for s in dashboard.slices if s.id not in keep]
        for chart in stale:
            dashboard.slices.remove(chart)
            logger.info(
                "detached chart '%s' from dashboard '%s' — no longer in the "
                "tile config",
                chart.slice_name,
                dashboard.slug,
            )
        if stale:
            db.session.commit()

    # Rewritten wholesale rather than merged into whatever is already there.
    # tiles.yaml is the source of truth for dashboard content, so a tile
    # removed from the config must lose its slot too — merging would leave the
    # removed tile's box behind as a permanent empty gap.
    for key, dashboard in dashboards.items():
        position = build_position_json(placements[key])
        dashboard.position_json = position
        # `#chart-id-<id>` is the DOM id Superset's own dashboard page puts on
        # each chart tile's wrapper element (verified against the installed
        # build's own frontend bundle) — a stable, native selector rather than
        # a guessed one. Rewritten wholesale each run, the same reasoning as
        # position_json above: a chart un-hidden in a later change must not
        # leave a stale hide rule behind.
        hidden_ids = sorted(hidden_chart_ids_by_dashboard[key])
        dashboard.css = (
            "\n".join(f"#chart-id-{cid} {{ display: none !important; }}" for cid in hidden_ids)
            if hidden_ids
            else ""
        )
        # Three native mechanisms for a visible per-chart hint were tried and
        # abandoned here (2026-09-18): `expanded_slices` (chart description,
        # forced-visible via metadata), `certified_by`/`certification_details`
        # (chart certification badge), and a native MARKDOWN caption tile
        # below each chart. All three reach the frontend with correct data
        # (verified via the API response a guest session actually receives)
        # but none render usably on a dashboard tile in this Superset version
        # — the first two never render at all (aria-label only), and the
        # MARKDOWN tile renders capped at a fixed ~268px width regardless of
        # what width is declared. Hint text, where a tile needs any, belongs
        # in the big-number viz's own `subheader` param (tiles.yaml) — the
        # one mechanism confirmed to render. The 4 KPI tiles carry none.
        # Nothing to set in json_metadata for this; just clearing stray keys
        # left over from the abandoned attempt.
        metadata = json.loads(dashboard.json_metadata or "{}")
        metadata.pop("expand_slices", None)
        metadata.pop("expanded_slices", None)
        dashboard.json_metadata = json.dumps(metadata)
        db.session.commit()
        logger.info(
            "dashboard '%s' laid out — %d tile(s) across %d row(s)",
            dashboard.slug,
            len(placements[key]),
            len(json.loads(position)["GRID_ID"]["children"]),
        )

    return charts_by_dataset, chart_id_by_name


FILTER_TYPES = {
    "select": "filter_select",
    "range": "filter_range",
    "time": "filter_time",
}


def apply_filters(db, filters: list[dict], datasets: dict, dashboards: dict,
                  charts_by_dataset: dict, chart_id_by_name: dict,
                  orientation: str = "HORIZONTAL") -> None:
    """Put the dashboards' filter bar together from config.

    A native filter is stored on the dashboard, not on a chart, which is what
    makes one dropdown drive every tile at once — unless the spec names a
    `charts:` list, in which case it drives only those tiles (D6; first used
    for the 4 per-KPI-tile date filters). Values are never listed here: a
    select filter reads its options from the column it targets, so the
    workflows, people and statuses offered are whatever the data currently
    holds — a new workflow appears in the dropdown with no change to this file.

    Filters narrow, they never widen. They are applied on top of the row
    filters minted per viewer, so a customer picking a name from a dropdown
    still only ever sees their own rows — the dropdown cannot reach past the
    guest token's own scope.
    """
    by_dashboard: dict[str, list[dict]] = {key: [] for key in dashboards}

    for spec in filters:
        missing = [k for k in ("name", "dashboard", "type") if not spec.get(k)]
        if missing:
            raise SystemExit(f"filter {spec!r} is missing required key(s): {missing}")

        filter_type = FILTER_TYPES.get(spec["type"])
        if filter_type is None:
            raise SystemExit(
                f"filter '{spec['name']}' has unknown type '{spec['type']}'. "
                f"Known types: {sorted(FILTER_TYPES)}"
            )

        dashboard_key = spec["dashboard"]
        if dashboard_key not in dashboards:
            raise SystemExit(
                f"filter '{spec['name']}' names dashboard '{dashboard_key}', "
                f"which is not provisioned. Known: {sorted(dashboards)}"
            )

        # A time filter carries no dataset: it applies the dashboard's time
        # range to each chart's own time column, so it spans datasets that do
        # not share a column name.
        if filter_type == "filter_time":
            targets: list[dict] = [{}]
            chart_names = spec.get("charts")
            if chart_names:
                # Scoped to specific tiles by name (D6), not every chart on
                # the dashboard — the first use of this narrowing, see OQ-16
                # in the spec.
                missing_charts = [n for n in chart_names if n not in chart_id_by_name]
                if missing_charts:
                    raise SystemExit(
                        f"filter '{spec['name']}' names chart(s) {missing_charts}, "
                        f"which are not in the tile config. Known charts: "
                        f"{sorted(chart_id_by_name)}"
                    )
                charts_in_scope = [chart_id_by_name[n] for n in chart_names]
            else:
                charts_in_scope = [
                    chart_id
                    for (dash, _dataset), ids in charts_by_dataset.items()
                    if dash == dashboard_key
                    for chart_id in ids
                ]
        else:
            dataset_name = spec.get("dataset")
            dataset = datasets.get(dataset_name)
            if dataset is None:
                raise SystemExit(
                    f"filter '{spec['name']}' names dataset '{dataset_name}', "
                    f"which is not registered. Known: {sorted(datasets)}"
                )
            column = spec.get("column")
            if not column:
                raise SystemExit(f"filter '{spec['name']}' needs a column")
            # Numeric `datasetId`, not `datasetUuid`. The live dashboard only
            # understands the id: `datasetUuid` is Superset's *export-file*
            # format, which its importer converts on the way in
            # (commands/dashboard/importers/v1/utils.py —
            # `target.pop("datasetUuid")` then `target["datasetId"] = …`).
            # Writing the uuid straight into json_metadata skips that
            # conversion, so the filter has no dataset it can query, never sends
            # a request, and every select dropdown renders "<NULL>" — while date
            # filters, which need no dataset, keep working and hide the fault.
            #
            # The earlier worry — that ids differ between installs — applies to
            # an exported file carried between machines, not here: `dataset` is
            # looked up live on this install every run, so its id is correct
            # for this install by construction.
            targets = [{"column": {"name": column}, "datasetId": dataset.id}]
            # Same `charts:` narrowing as the time-filter branch above (D6,
            # OQ-16) — without it, every chart sharing this dataset on the
            # dashboard picks up the filter, which is wrong the moment two
            # charts on the same dataset need different filters (e.g. one
            # keyed on days_to_due, another that should ignore it entirely).
            chart_names = spec.get("charts")
            if chart_names:
                missing_charts = [n for n in chart_names if n not in chart_id_by_name]
                if missing_charts:
                    raise SystemExit(
                        f"filter '{spec['name']}' names chart(s) {missing_charts}, "
                        f"which are not in the tile config. Known charts: "
                        f"{sorted(chart_id_by_name)}"
                    )
                charts_in_scope = [chart_id_by_name[n] for n in chart_names]
            else:
                charts_in_scope = charts_by_dataset.get(
                    (dashboard_key, dataset_name), []
                )

        if not charts_in_scope:
            # A filter nothing listens to renders as a live control that does
            # nothing when used, which reads as broken rather than absent.
            logger.warning(
                "filter '%s' matches no chart on dashboard '%s' — skipped",
                spec["name"],
                dashboard_key,
            )
            continue

        # Deterministic id, derived from the name. Superset generates a random
        # one per filter; re-running provisioning with random ids would append
        # a duplicate set on every run instead of updating the same filters.
        slug = re.sub(r"[^A-Za-z0-9]+", "-", spec["name"]).strip("-").lower()

        # A range filter's own default, applied on first load without the
        # viewer touching the control (e.g. "Days To Due" opening pre-set to
        # 0-7). Shaped to match what the NumericalRange filter plugin itself
        # writes into defaultDataMask when a viewer drags it — two adhoc
        # filters (>=, <=) plus the [min, max] pair the slider reads back.
        default_min = spec.get("default_min")
        default_max = spec.get("default_max")
        if filter_type == "filter_range" and (
            default_min is not None or default_max is not None
        ):
            default_data_mask = {
                "extraFormData": {
                    "filters": [
                        f
                        for f in (
                            {"col": column, "op": ">=", "val": default_min}
                            if default_min is not None
                            else None,
                            {"col": column, "op": "<=", "val": default_max}
                            if default_max is not None
                            else None,
                        )
                        if f is not None
                    ]
                },
                "filterState": {"value": [default_min, default_max]},
                "ownState": {},
            }
        else:
            default_data_mask = {
                "extraFormData": {},
                "filterState": {},
                "ownState": {},
            }

        by_dashboard[dashboard_key].append(
            {
                "id": f"NATIVE_FILTER-openwind-{slug}",
                "name": spec["name"],
                "filterType": filter_type,
                "type": "NATIVE_FILTER",
                "targets": targets,
                "controlValues": {
                    "enableEmptyFilter": False,
                    "defaultToFirstItem": False,
                    "multiSelect": spec.get("multi_select", True),
                    # Search the whole column rather than the loaded page —
                    # a ticket dropdown has hundreds of entries, and without
                    # this only the first page is reachable by typing.
                    "searchAllOptions": spec.get("search_all", True),
                    "inverseSelection": False,
                },
                "defaultDataMask": default_data_mask,
                "cascadeParentIds": [],
                "scope": {"rootPath": ["ROOT_ID"], "excluded": []},
                "chartsInScope": charts_in_scope,
                "tabsInScope": [],
                "description": spec.get("description", ""),
            }
        )

    for key, dashboard in dashboards.items():
        metadata = json.loads(dashboard.json_metadata or "{}")
        # Replaced wholesale: config is the source of truth, so a filter
        # removed from it must disappear rather than linger as a control the
        # config no longer describes.
        metadata["native_filter_configuration"] = by_dashboard[key]
        # Horizontal by default: the vertical bar is a fixed left column, and
        # inside an embed that column is taken from an already narrow panel and
        # charged to every tile. Across the top it sits on one row above the
        # content, which is also where the reader looks for controls.
        metadata["filter_bar_orientation"] = orientation
        dashboard.json_metadata = json.dumps(metadata)
        db.session.commit()
        logger.info(
            "dashboard '%s': %d filter(s) configured, bar %s",
            dashboard.slug,
            len(by_dashboard[key]),
            orientation.lower(),
        )


def ensure_dashboard(db, title: str, slug: str, allowed_domain: str, service_account_user):
    """Create a dashboard addressed by slug, and mark it embeddable.

    Addressed by slug, never by UUID: the embedded identifier the mint endpoint
    needs is generated by Superset (EmbeddedDashboardDAO.upsert takes no uuid),
    so it cannot be pinned from configuration. Hardcoding one in application
    source is what spec R17 forbids, and it breaks on a fresh clone — the
    literal would not match whatever provisioning generated here, and every
    dashboard call behind a successfully minted pass would 404.

    The slug is stable and comes from configuration, so the API resolves the
    embedded id at runtime via GET /api/v1/dashboard/<slug>/embedded.
    """
    from superset.daos.dashboard import EmbeddedDashboardDAO
    from superset.models.dashboard import Dashboard

    dashboard = db.session.query(Dashboard).filter_by(slug=slug).one_or_none()
    created = dashboard is None
    if created:
        dashboard = Dashboard(dashboard_title=title, slug=slug, published=True)
        db.session.add(dashboard)
        db.session.commit()
        logger.info("created dashboard '%s' (slug=%s)", title, slug)
    elif dashboard.dashboard_title != title:
        # Renaming has to be handled explicitly. The slug is the identity here
        # (it is what the mint endpoint resolves), so a dashboard found by slug
        # keeps whatever title it was created with unless it is updated — which
        # made a rename in configuration look like it had applied when it had
        # not.
        logger.info(
            "dashboard '%s' renamed to '%s' (slug=%s)",
            dashboard.dashboard_title,
            title,
            slug,
        )
        dashboard.dashboard_title = title
        db.session.commit()
    else:
        logger.info("dashboard '%s' (slug=%s) already present", title, slug)

    # A dashboard created outside a login context (as this one is — a
    # provisioning script, not an interactive user) has no owner. Found live,
    # not anticipated: Superset's dashboard visibility check hides an
    # ownerless dashboard from everyone except `admin`, so GET
    # .../embedded returned 404 for the service account even after it had
    # can_read on Dashboard — the permission was granted, the specific row
    # was simply invisible to it. Ownership, not a broader permission, is the
    # correct fix: it grants visibility into exactly these two dashboards,
    # not dashboards generally.
    if service_account_user not in dashboard.owners:
        dashboard.owners.append(service_account_user)
        db.session.commit()
        logger.info("added service account as owner of dashboard '%s'", slug)

    # Idempotent: upsert rotates nothing on a dashboard that is already
    # embeddable, so re-running provisioning never invalidates a live embed.
    embedded = EmbeddedDashboardDAO.upsert(dashboard, [allowed_domain])
    db.session.commit()
    logger.info(
        "dashboard '%s' embeddable — embedded uuid %s, allowed domain %s",
        slug,
        embedded.uuid,
        allowed_domain,
    )
    return dashboard


def main() -> int:
    from superset.app import create_app

