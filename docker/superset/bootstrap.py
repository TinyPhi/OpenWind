        ensure_guest_role(security_manager, db, guest_role_name)
        service_account_user = ensure_service_account(
            security_manager, db, service_user, service_password
        )
        reporting_database = ensure_reporting_database(
            db, reporting_db_name, reporting_uri
        )
        close_sqllab_exposure_elsewhere(db, reporting_db_name)

        # The dataset every tile is built from.
        #
        # `workflow_events_masked` used to be registered here too. It is gone:
        # migration 0119 dropped it because it could never work. The view read
        # `metadata` in order to redact it, and 0112's `security_invoker = true`
        # means the caller's own privileges are checked against every column the
        # view touches — so an analyst could use it only while also holding the
        # raw column it existed to hide. It never returned a row.
        #
        # Event classification now comes from `workflow_events.event_type`
        # (migration 0117), a trigger-maintained mirror of metadata->>'type',
        # which was the only key any dataset ever read from the payload. The
        # payload itself is no longer granted to the reporting role at all
        # (migration 0118), so masking is achieved by exclusion rather than
        # redaction. See docs/specs/reporting-metadata-masking-repair.md.
        # The role, not the user — datasource_access is granted on the role,
        # matching every other permission the service account holds. Looked up
        # by name rather than reused from ensure_service_account's return value
        # because that function returns the user, not the role.
        # Stage 2 roles. Harmless when Stage 2 is off — the roles exist, but
        # nothing maps a login onto them.
        ensure_analyst_roles(security_manager, db, reporting_database)

        # Before registering this run's datasets, clear the ones that should no
        # longer exist. Ordered first so a dataset this run is about to create
        # cannot be mistaken for a leftover, and so the retired names are gone
        # before anything looks them up.
        remove_retired_datasets(db, reporting_db_name)

        reporting_role = security_manager.find_role("ReportingServiceAccount")

        # Keyed by table name so tiles can name their dataset in the config
        # rather than carrying an id that differs per deployment (spec R17).
        datasets = {
            name: ensure_dataset(
                db,
                security_manager,
                reporting_role,
                reporting_database,
                name,
                "created_at",
            )
            for name in ("entity_instances",)
        }

        # `current_state` is stored as a machine token (`in_progress`) and
        # reaches a chart axis and tooltip exactly as stored. Humanised once
        # here so every tile on this dataset agrees, rather than per tile. The
        # raw column is untouched and remains the one to filter on — state
        # names are workflow-defined, so a filter has to match the stored
        # value, not its display form.
        ensure_dataset(
            db,
            security_manager,
            reporting_role,
            reporting_database,
            "entity_instances",
            "created_at",
            calculated_columns=[
                {
                    "name": "state",
                    "expression": "INITCAP(REPLACE(current_state, '_', ' '))",
                    "type": "TEXT",
                    "verbose_name": "Status",
                },
                # Names, not subject ids, on the charts built from this table.
                # A scalar sub-query rather than a join, because a calculated
                # column is an expression on this dataset's own table — there
                # is no FROM clause here to add a join to. (Superset's
                # no-sub-query rule applies to chart-level ad-hoc filters, not
                # to dataset column expressions; confirmed against the running
                # instance.) tenant_users carries RLS, so the lookup cannot
                # reach across tenants, and falls back to the id for anyone
                # with no name stored yet.
                {
                    "name": "assignee_name",
                    "expression": (
                        "COALESCE((SELECT tu.display_name FROM tenant_users tu "
                        "WHERE tu.user_id = entity_instances.assigned_to "
                        "AND tu.tenant_id = entity_instances.tenant_id), "
                        "entity_instances.assigned_to)"
                    ),
                    "type": "TEXT",
                    # "Assigned To", not "Assignee" — ticket_list's own column
                    # uses "Assigned To"; one dataset calling the same idea two
                    # names was exactly the drift the nomenclature rule exists
                    # to catch.
                    "verbose_name": "Assigned To",
                },
                # Open vs closed, asked of each workflow's own definition
                # rather than matched against a list of state names. The same
                # word means different things per workflow — Helpdesk closes at
                # `resolved`, Purchase Approval at `received`/`rejected`,
                # Reimbursement at `closed` — so any hardcoded list is wrong for
                # every workflow but the one it was written for, and silently
                # so. A workflow added tomorrow classifies correctly with no
                # change here.
                #
                # 'Unknown' is deliberately a visible bucket, not a silent
                # drop: rows whose current_state has no matching workflow_states
                # row exist (the `initial` dead ends), and counting them as
                # open or closed would be a guess.
                {
                    "name": "state_group",
                    "expression": (
                        "COALESCE((SELECT CASE WHEN ws.is_terminal THEN 'Closed' "
                        "ELSE 'Open' END FROM workflow_states ws "
                        "WHERE ws.workflow_id = entity_instances.workflow_id "
                        "AND ws.name = entity_instances.current_state), 'Unknown')"
                    ),
                    "type": "TEXT",
                    "verbose_name": "Open / Closed",
                },
                # Workflow name, so the Org Overview filter bar can narrow the
                # chart tiles by process. entity_instances stores only the id.
                {
                    "name": "workflow_name",
                    "expression": (
                        "COALESCE((SELECT w.name FROM workflows w "
                        "WHERE w.id = entity_instances.workflow_id), 'None')"
                    ),
                    "type": "TEXT",
                    "verbose_name": "Workflow",
                },
                {
                    "name": "raiser_name",
                    "expression": (
                        "COALESCE((SELECT tu.display_name FROM tenant_users tu "
                        "WHERE tu.user_id = entity_instances.created_by "
                        "AND tu.tenant_id = entity_instances.tenant_id), "
                        "entity_instances.created_by)"
                    ),
                    "type": "TEXT",
                    "verbose_name": "Raised By",
                },
            ],
        )

        # Virtual dataset: how long a ticket sat in each state, sum of every
        # visit (decided 2026-09 — reopens add to the total rather than only
        # the longest stretch). Excludes comments, which are workflow_events
        # rows with from_state = to_state and would otherwise cut a real dwell
        # period in two.
        #
        # tenant_id is carried through unmodified so the mint-time row filter
        # still binds to a real column — a virtual dataset that dropped it
        # would make the tenant clause a no-op rather than a refusal.
        datasets["ticket_dwell_time"] = ensure_dataset(
            db,
            security_manager,
            reporting_role,
            reporting_database,
            "ticket_dwell_time",
            "created_at",
            sql="""
                SELECT
                    tenant_id,
                    instance_id,
                    to_state,
                    created_at,
                    EXTRACT(EPOCH FROM (
                        LEAD(created_at) OVER (
                            PARTITION BY instance_id ORDER BY created_at
                        ) - created_at
                    )) / 3600.0 AS dwell_hours
                FROM workflow_events
                WHERE COALESCE(event_type, 'transition') <> 'comment'
            """,
            # Confirmed against this exact query's cursor.description on the
            # live connection, not assumed from the SQL — see the comment on
            # ensure_dataset's `columns` parameter for why this is necessary
            # here at all.
            columns=[
                {"name": "tenant_id", "type": "UUID"},
                {"name": "instance_id", "type": "UUID"},
                {"name": "to_state", "type": "TEXT"},
                {"name": "created_at", "type": "TIMESTAMP WITH TIME ZONE", "is_dttm": True},
                {"name": "dwell_hours", "type": "DOUBLE PRECISION"},
            ],
        )

        # Virtual dataset: time to first response per ticket. A LATERAL join,
        # not a sub-query in a filter — the restriction hit earlier
        # (ADHOC_SUBQUERY_NOT_ALLOWED_ERROR) is specific to ad-hoc chart
        # filters; a dataset's own defining query is raw SQL and unaffected by
        # it, already confirmed for the dwell-time dataset above.
        #
        # `actor_id <> created_by` is what "response" means here: the first
        # comment from someone other than the ticket's own creator, matching
        # the reporting spec's correction that time-to-first-response is
        # buildable at all (comments carry real timestamps, contrary to an
        # earlier version of the spec's "no reply timestamp exists" claim).
        datasets["ticket_first_response"] = ensure_dataset(
            db,
            security_manager,
            reporting_role,
            reporting_database,
            "ticket_first_response",
            "replied_at",
            sql="""
                SELECT
                    ei.id AS instance_id,
                    ei.tenant_id,
                    ei.created_by,
                    ei.assigned_to,
                    fr.actor_id AS responder_id,
                    COALESCE(
                        (SELECT tu.display_name FROM tenant_users tu
                         WHERE tu.tenant_id = ei.tenant_id
                           AND tu.user_id = fr.actor_id),
                        fr.actor_id
                    ) AS responder,
                    fr.replied_at,
                    EXTRACT(EPOCH FROM (fr.replied_at - ei.created_at)) / 3600.0
                        AS hours_to_first_response
                FROM reporting_instances ei
                JOIN LATERAL (
                    SELECT we.actor_id, we.created_at AS replied_at
                    FROM workflow_events we
                    WHERE we.instance_id = ei.id
                      AND we.event_type = 'comment'
                      AND we.actor_id <> ei.created_by
                    ORDER BY we.created_at ASC
                    LIMIT 1
                ) fr ON true
            """,
            columns=[
                {"name": "instance_id", "type": "UUID"},
                {"name": "tenant_id", "type": "UUID"},
                {"name": "created_by", "type": "TEXT"},
                {"name": "assigned_to", "type": "TEXT"},
                # The raw subject stays available for anything that needs to
                # match on identity; tiles show the name.
                {"name": "responder_id", "type": "TEXT"},
                # Falls back to the subject id for anyone with no name stored
                # yet — tenant_users is filled from the JWT at sign-in, so a
                # user who has never logged in has no name to show.
                {"name": "responder", "type": "TEXT", "verbose_name": "Responder"},
                {"name": "replied_at", "type": "TIMESTAMP WITH TIME ZONE", "is_dttm": True},
                {"name": "hours_to_first_response", "type": "DOUBLE PRECISION"},
            ],
        )

        # Virtual dataset: one row per ticket, for the per-ticket tiles a
        # purely aggregate dashboard cannot answer — which ticket, held by
        # whom, in what state, and how long it has cost so far.
        #
        # `title` is the one field lifted out of the `fields` JSONB, and it is
        # lifted by name on purpose. Postgres cannot grant SELECT on a single
        # key of a JSONB column — the grant is all-or-nothing per column — so
        # the restriction spec §C/§V asks for cannot be enforced at the
        # database. It is enforced here instead: this dataset declares `title`
        # and nothing else from `fields`, and a tile can only read a column its
        # dataset declares. `description`, `body` and the `__accessUsers` grant
        # list therefore stay unreachable from any chart, which is the point of
        # the restriction.
        #
        # LEFT JOIN, not JOIN: a ticket with no transitions yet has no dwell
        # row, and an inner join would silently drop exactly the newest tickets
        # — the ones most likely to need attention.
        #
        # `sno` is a display serial: 1 is the newest ticket, counting down the
        # page. Two things have to line up for it to read as 1, 2, 3.
        #
        # First, the window is partitioned by tenant_id. Superset wraps a
        # virtual dataset as a subquery and applies row filters *outside* it
        # (confirmed on the generated SQL), so a window function here runs
        # before filtering — an unpartitioned ROW_NUMBER() would number every
        # row in the table and then hand a filtered view rows 47, 112, 190.
        # Partitioning by the same column the tenant filter uses makes the two
        # agree, so the surviving rows are numbered 1..N with no gaps.
        #
        # Second, the tile must sort by the same key the window orders by
        # (created_at DESC — see tiles.yaml). Sort the table by anything else
        # and the serials are still correct, just no longer in sequence down
        # the page, which is how a serial column behaves in any table.
        #
        # This does not extend to the per-user dashboard: its filter is
        # assigned_to/created_by, and no single partition matches a predicate
        # over two columns. The personal tile therefore does not show a serial
        # rather than showing one that skips.
        #
        # `current_state` is humanised here rather than in each tile, so every
        # chart reading this dataset agrees on how a state is spelled. Note it
        # leaves the raw value behind: entity_instances still carries the
        # machine state for any tile that needs to filter on it exactly.
        # One ticket, one row. Held in a local because the same query is
        # registered three times under different names — see below.
        # embed_origin is baked in at provisioning time as a SQL string
        # literal, not read at query time — it never changes per row, and
        # ei.id already carries the raw single-quote risk this repo's SQL
        # writes handle by construction (uuid values, not user text).
        _embed_origin_sql = embed_origin.replace("'", "''")
        ticket_sql = f"""
                SELECT
                    ei.id AS instance_id,
                    ei.tenant_id,
                    ROW_NUMBER() OVER (
                        PARTITION BY ei.tenant_id
                        ORDER BY ei.created_at DESC, ei.id
                    ) AS sno,
                    ei.reporting_title AS title,
                    INITCAP(REPLACE(ei.current_state, '_', ' ')) AS current_state,
                    w.name AS workflow_name,
                    COALESCE(NULLIF(au.display_name, ei.assigned_to), ei.assigned_to)
                        AS assignee,
                    COALESCE(NULLIF(cu.display_name, ei.created_by), ei.created_by)
                        AS raiser,
                    ei.assigned_to,
                    ei.created_by,
                    ei.created_at,
                    ei.due_date,

                    -- Superset's raw table mode mishandles a genuinely
                    -- temporal column (is_dttm=True) placed directly in
                    -- all_columns -- it comes back blank in the grid. A
                    -- plain text rendering, same trick as `title`/
                    -- `department` above, sidesteps that entirely.
                    CASE WHEN ei.due_date IS NULL THEN NULL
                         ELSE TO_CHAR(ei.due_date, 'YYYY-MM-DD HH24:MI')
                    END AS due_date_display,

                    -- Same trick, for created_at.
                    TO_CHAR(ei.created_at, 'YYYY-MM-DD HH24:MI')
                        AS created_at_display,

                    -- Whole days, created to now. Seconds/86400 rather than
                    -- EXTRACT(DAY FROM interval), which counts calendar day
                    -- boundaries and reports 0 for a ticket opened 23h ago.
                    GREATEST(0, EXTRACT(EPOCH FROM (now() - ei.created_at)) / 86400.0)::int
                        AS days_open,

                    -- Signed on purpose: negative is overdue, and a single
                    -- column that carries both lets one colour scale run from
                    -- comfortable through due to breached.
                    CASE WHEN ei.due_date IS NULL THEN NULL
                         ELSE (EXTRACT(EPOCH FROM (ei.due_date - now())) / 86400.0)::int
                    END AS days_to_due,

                    ROUND(fr.first_response_hours::numeric, 1) AS first_response_hours,
                    ROUND(cl.time_to_close_hours::numeric, 1) AS time_to_close_hours,
                    ROUND(
                        (EXTRACT(EPOCH FROM (now() - lc.last_comment_at)) / 3600.0)::numeric,
                        1
                    ) AS hours_since_last_comment,

                    -- SLA comes from the workflow's own state definition. Most
                    -- workflows have not set one, so 'No SLA' is a real third
                    -- state rather than a silent pass: a ticket with no target
                    -- must not be reported as meeting it.
                    ws.sla_hours,
                    CASE
                        WHEN ws.sla_hours IS NULL THEN 'No SLA'
                        WHEN ei.created_at + (ws.sla_hours || ' hours')::interval < now()
                            THEN 'Breached'
                        ELSE 'Within SLA'
                    END AS sla_state,

                    -- Margin against the SLA target: positive means closed
                    -- with room to spare, negative means it breached and by
                    -- how much. NULL wherever there is no SLA or the ticket
                    -- has not closed — a histogram of this column is
                    -- therefore only ever built over tickets that both have a
                    -- target and a real close time, never over a mix that
                    -- would misrepresent tickets with no target as "on time".
                    ROUND((ws.sla_hours - cl.time_to_close_hours)::numeric, 1)
                        AS sla_margin_hours,

                    -- Same scoping as sla_margin_hours above (closed tickets
                    -- with a real SLA target only), but as a bucket rather
                    -- than a number -- built for "who is missing SLA",
                    -- grouped by assignee, not "by how much".
                    CASE
                        WHEN cl.time_to_close_hours IS NULL THEN NULL
                        WHEN ws.sla_hours IS NULL THEN 'No SLA Target'
                        WHEN ws.sla_hours - cl.time_to_close_hours >= 0
                            THEN 'Before SLA'
                        ELSE 'After SLA'
                    END AS sla_outcome,

                    -- Raw timestamp for the same close event time_to_close_hours
                    -- already measures. Needed as its own column so a
                    -- time-series chart has a real x-axis to plot SLA outcome
                    -- against week-by-week, rather than only the derived hour
                    -- count.
                    cl.closed_at,

                    -- The URL slug the OpenWind app itself derives at runtime
                    -- (entity-type-context.tsx: toTypeSlug(plural||name)),
                    -- computed here identically so a table row can be turned
                    -- into a real /records/<slug>/<id> link without a second
                    -- source of truth for how that slug is built.
                    REGEXP_REPLACE(
                        REGEXP_REPLACE(
                            LOWER(COALESCE(NULLIF(et.plural, ''), et.name, 'record')),
                            '\s+', '-', 'g'
                        ),
                        '[^a-z0-9-]', '', 'g'
                    ) AS record_type_slug,

                    -- A real, clickable link, rendered as HTML in the table
                    -- cell (allow_render_html on the chart). target="_blank"
                    -- needs no extra iframe permission: the embed SDK's
                    -- sandbox already includes allow-popups by default
                    -- (verified against its own source), which is exactly
                    -- what a target="_blank" anchor needs. This does not
                    -- depend on cross-filtering or postMessage working inside
                    -- the embed at all — it is a plain link a browser already
                    -- knows how to follow.
                    '<a href="{_embed_origin_sql}/records/record/' ||
                        ei.id ||
                        '" target="_blank" rel="noopener">Open &rarr;</a>'
                        AS open_link,

                    -- Placeholders. The fields are being built by the platform
                    -- team; the columns exist now so the tiles and the funnel
                    -- can be laid out and reviewed, and start carrying real
                    -- values the moment the fields land — at which point these
                    -- three lines become the only edit needed.
                    -- Open vs closed asked of the workflow's own definition,
                    -- never matched against state names: Helpdesk closes at
                    -- `resolved`, Purchase Approval at `received`, and a
                    -- hardcoded list is wrong for every workflow but one.
                    COALESCE(ws.is_terminal, false) AS is_closed,

                    'Not set'::text AS severity,

                    -- Priority, and NOT the same thing as the severity
                    -- placeholder above it. Severity has no field definition
                    -- anywhere in entity_fields and so has no source to read;
                    -- priority is a real seeded field, well populated
                    -- (low 88, urgent 79, high 74, medium 59, unset 6), and
                    -- until now Superset exposed none of it. "High priority
                    -- tickets due this week" was unanswerable here while
                    -- looking answerable, because the severity dropdown was
                    -- sitting there offering a single value.
                    --
                    -- Read from the projection column (migration 0123), not
                    -- from the payload: reporting is not granted `fields`
                    -- (0122). Tidied for display here rather than in the
                    -- column, so the column stays an exact mirror — same split
                    -- as `current_state` and its humanised `state`.
                    INITCAP(COALESCE(NULLIF(ei.reporting_priority, ''), 'Not set'))
                        AS priority,
                    -- Real now (2026-09-21) — the `department` custom field
                    -- is seeded for the ticket entity type
                    -- (modules/helpdesk/seed/001_entity_types.sql), so this
                    -- reads the same jsonb column the `title` extraction
                    -- above already uses, rather than the placeholder the
                    -- other two lines still carry.
                    ei.reporting_department AS department,
                    'Not set'::text AS team_service,

                    COALESCE(d.total_hours, 0) AS total_hours
                FROM reporting_instances ei
                LEFT JOIN entity_types et ON et.id = ei.entity_type_id
                LEFT JOIN workflows w ON w.id = ei.workflow_id
                LEFT JOIN workflow_states ws
                    ON ws.workflow_id = ei.workflow_id AND ws.name = ei.current_state
                LEFT JOIN tenant_users au
                    ON au.tenant_id = ei.tenant_id AND au.user_id = ei.assigned_to
                LEFT JOIN tenant_users cu
                    ON cu.tenant_id = ei.tenant_id AND cu.user_id = ei.created_by

                -- First reply by anyone other than the person who raised it.
                LEFT JOIN LATERAL (
                    SELECT EXTRACT(EPOCH FROM (we.created_at - ei.created_at))/3600.0
                               AS first_response_hours
                    FROM workflow_events we
                    WHERE we.instance_id = ei.id
                      AND we.event_type = 'comment'
                      AND we.actor_id <> ei.created_by
                    ORDER BY we.created_at ASC LIMIT 1
                ) fr ON true

                -- First arrival in a state the workflow calls terminal. Asked
                -- of workflow_states rather than matched against state names,
                -- which differ per workflow.
                LEFT JOIN LATERAL (
                    SELECT
                        EXTRACT(EPOCH FROM (we.created_at - ei.created_at))/3600.0
                            AS time_to_close_hours,
                        we.created_at AS closed_at
                    FROM workflow_events we
                    JOIN workflow_states t
                      ON t.workflow_id = ei.workflow_id
                     AND t.name = we.to_state
                     AND t.is_terminal
                    WHERE we.instance_id = ei.id
                    ORDER BY we.created_at ASC LIMIT 1
                ) cl ON true

                LEFT JOIN LATERAL (
                    SELECT we.created_at AS last_comment_at
                    FROM workflow_events we
                    WHERE we.instance_id = ei.id AND we.event_type = 'comment'
                    ORDER BY we.created_at DESC LIMIT 1
                ) lc ON true

                LEFT JOIN (
                    SELECT instance_id, SUM(dwell_hours) AS total_hours
                    FROM (
                        SELECT
                            instance_id,
                            EXTRACT(EPOCH FROM (
                                LEAD(created_at) OVER (
                                    PARTITION BY instance_id ORDER BY created_at
                                ) - created_at
                            )) / 3600.0 AS dwell_hours
                        FROM workflow_events
                        WHERE COALESCE(event_type, 'transition') <> 'comment'
                    ) w
                    WHERE dwell_hours IS NOT NULL
                    GROUP BY instance_id
                ) d ON d.instance_id = ei.id
                WHERE ei.deleted_at IS NULL
                  AND ei.reporting_title IS NOT NULL
            """
