        service_user = os.environ["SUPERSET_SERVICE_ACCOUNT_USER"]
        service_password = os.environ["SUPERSET_SERVICE_ACCOUNT_PASSWORD"]

        logger.info("provisioning reporting — guest role '%s'", guest_role_name)

        # Order matters: revoke from anonymous first, so a failure later still
        # leaves the instance no more exposed than it would have been.
